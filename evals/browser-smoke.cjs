const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
const fs=require('node:fs/promises');
const path=require('node:path');
(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:process.env.CHROME_EXECUTABLE||undefined});
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 const errors=[],external=[];
 page.on('pageerror',e=>errors.push(e.message));
 page.on('request',r=>{if(!r.url().startsWith('http://127.0.0.1:8000')&&!r.url().startsWith('data:')&&!r.url().startsWith('blob:'))external.push(r.url())});
 const folder=path.resolve('docs/screenshots');await fs.mkdir(folder,{recursive:true});
 await page.goto('http://127.0.0.1:8000');
 await page.getByRole('heading',{name:'Practice the interview your resume starts.'}).waitFor();
 await page.screenshot({path:path.join(folder,'hero-desktop.png'),fullPage:true});
 const primary=await page.getByRole('button',{name:'Prepare my interview'}).nth(1).boundingBox();
 await page.getByRole('button',{name:'See an example'}).click();
 await page.getByRole('dialog').waitFor();await page.keyboard.press('Escape');
 if(await page.getByRole('dialog').count())throw new Error('Example dialog did not close with Escape');
 await page.setViewportSize({width:360,height:800});
 await page.screenshot({path:path.join(folder,'hero-mobile-360.png'),fullPage:true});
 const overflow=await page.evaluate(()=>({viewport:innerWidth,document:document.documentElement.scrollWidth}));
 await page.getByRole('button',{name:'Prepare my interview'}).nth(1).click();
 await page.getByLabel('Owner key').fill('synthetic-browser-acceptance-owner-key');
 await page.getByRole('button',{name:'Sign in',exact:true}).click();
 await page.getByRole('heading',{name:'Let’s make this feel like your interview.'}).waitFor();
 await page.screenshot({path:path.join(folder,'setup-mobile-360.png'),fullPage:true});
 const result={stage:'landing-and-auth',primary_visible:primary&&primary.y+primary.height<1000,overflow,errors,external_requests:external};
 await fs.writeFile('docs/browser-results.json',JSON.stringify(result,null,2));console.log(JSON.stringify(result));
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
